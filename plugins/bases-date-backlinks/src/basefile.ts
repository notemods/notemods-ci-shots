export const BASE_VIEW_ID = 'bases-date-backlinks';
export const BASE_FILE_PATH = 'Date Property Backlinks.base';
export const BASE_MARKER = '# Generated by Date Property Backlinks';

/** Returns the smallest Base file that can be embedded in daily notes. */
export function buildBaseText(dateFormat = 'YYYY-MM-DD'): string {
	return `${BASE_MARKER}\ndateBacklinksManaged: true\n\nfilters:\n  and:\n    - 'file.ext == "md"'\n    - 'formula.dateBacklinksHasDate'\n\nformulas:\n  dateBacklinksHasDate: 'note["date"] != null'\n\nviews:\n  - type: ${BASE_VIEW_ID}\n    name: Date backlinks\n    matchProperty: note.date\n    dailyNoteDate: file.name\n    dailyNoteFormat: ${JSON.stringify(dateFormat)}\n`;
}

/** The command may reuse only the file that it generated for this view. */
export function isManagedBase(text: string): boolean {
	return (text.startsWith(BASE_MARKER) || /^dateBacklinksManaged: true\s*$/m.test(text)) && /^\s+-\s*type:\s*bases-date-backlinks\s*$/m.test(text);
}

/** Appends an embed once and keeps the note's line ending style. */
export function insertEmbed(noteText: string, embed: string): string {
	if (hasEmbed(noteText) || noteText.split(/\r?\n/).some((line) => line.trim() === embed)) return noteText;
	const newline = noteText.includes('\r\n') ? '\r\n' : '\n';
	const gap = noteText.length === 0 ? '' : noteText.endsWith(newline) ? newline : `${newline}${newline}`;
	return `${noteText}${gap}${embed}${newline}`;
}

/** Recognizes wiki and Markdown embeds, including aliases and relative paths. */
export function hasEmbed(text: string): boolean {
	return /!\[\[(?:[^\]\n]*\/)?Date Property Backlinks(?:\.base)?(?:[|#][^\]\n]*)?\]\]/i.test(text) ||
		/!\[[^\]\n]*\]\((?:[^)\n]*\/)?Date(?: |%20)Property(?: |%20)Backlinks\.base(?:#[^)\n]*)?\)/i.test(text);
}

/** Update only our named formula; keep filters and other user fields intact. */
export function updatePropertyFilter(text: string, properties: readonly string[]): string {
	if (!isManagedBase(text)) return text;
	const names = [...new Set(properties.filter((id) => id.startsWith('note.')).map((id) => id.slice(5)))];
	const expression = names.length ? names.map((name) => `note[${JSON.stringify(name)}] != null`).join(' || ') : 'true';
	return text.replace(/^ {2}dateBacklinksHasDate: .*$/m, `  dateBacklinksHasDate: ${JSON.stringify(expression)}`);
}
