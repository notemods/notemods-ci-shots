import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { readFile } from 'node:fs/promises';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

// docx 9.10.0 browser build: five edits so that tools/network-gate.mjs can read main.js. Each edit must match exactly
// the expected number of times, so a library update that changes the code fails the build instead of shipping unpatched.
//   - pako (inside jszip) keeps its deflate and inflate buffers in a field named "window". The gate reads x.window[i]
//     as a computed lookup on the global object. The edit renames the field to "slidingWindow". It is a plain object field.
//   - The setImmediate polyfill turns a string argument into code with new Function. docx always gives a function.
//     The edit throws a TypeError for a string instead.
//   - Three polyfills make functions from strings: function-bind (only a fallback when Function.prototype.bind is
//     missing), is-generator-function and get-intrinsic (both catch a failure, as under a strict CSP). The edits give
//     the same result as that failure path.
const DOCX_EDITS = [
	{ from: /\.window(?![\w$])/g, to: '.slidingWindow', count: 36 },
	{ from: '(e = new Function("" + e))', to: '(e = function() { throw new TypeError("setImmediate needs a function"); })', count: 1 },
	{ from: 'bound = Function("binder", "return function (" + joiny(boundArgs, ",") + "){ return binder.apply(this,arguments); }")(binder);', to: 'throw new TypeError("Function.prototype.bind is missing");', count: 1 },
	{ from: 'return Function("return function*() {}")();', to: 'return void 0;', count: 1 },
	{ from: 'return $Function("\\"use strict\\"; return (" + expressionSyntax + ").constructor;")();', to: 'return void expressionSyntax;', count: 1 },
	// Two setImmediate polyfills (immediate in lie, and the copy in jszip) keep an old-IE path that creates a script
	// element. The directory review flags createElement('script'). Electron never takes that path; the edits remove it
	// and keep the setTimeout fallback.
	{ from: /"document" in t && "onreadystatechange" in t\.document\.createElement\("script"\) \? function\(\) \{\s*var e = t\.document\.createElement\("script"\);\s*e\.onreadystatechange = function\(\) \{\s*u\(\), e\.onreadystatechange = null, e\.parentNode\.removeChild\(e\), e = null;\s*\}, t\.document\.documentElement\.appendChild\(e\);\s*\} : /g, to: '', count: 1 },
	{ from: /l && "onreadystatechange" in l\.createElement\("script"\) \? \(s = l\.documentElement, function\(e\) \{\s*var t = l\.createElement\("script"\);\s*t\.onreadystatechange = function\(\) \{\s*c\(e\), t\.onreadystatechange = null, s\.removeChild\(t\), t = null;\s*\}, s\.appendChild\(t\);\s*\}\) : /g, to: '', count: 1 },
];

const patchDocx = {
	name: 'patch-docx',
	setup(build) {
		build.onLoad({ filter: /[\\/]docx[\\/]dist[\\/]index\.mjs$/ }, async (args) => {
			let code = await readFile(args.path, 'utf8');
			for (const edit of DOCX_EDITS) {
				const found = typeof edit.from === 'string' ? code.split(edit.from).length - 1 : (code.match(edit.from) ?? []).length;
				if (found !== edit.count) throw new Error(`patch-docx: expected ${edit.count} match(es) of ${String(edit.from).slice(0, 60)}, found ${found}`);
				code = typeof edit.from === 'string' ? code.split(edit.from).join(edit.to) : code.replace(edit.from, edit.to);
			}
			if (/(?<![\w$.])\$?Function\(|\.window\[/.test(code)) throw new Error('patch-docx: a Function constructor call or a .window[ lookup is left in the library');
			if (code.includes('createElement("script")')) throw new Error('patch-docx: a script element is left in the library');
			return { contents: code, loader: 'js' };
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
	plugins: [patchDocx],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
