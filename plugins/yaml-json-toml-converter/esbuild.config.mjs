import esbuild from 'esbuild';
import process from 'process';
import { readFile } from 'node:fs/promises';
import { builtinModules } from 'node:module';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	plugins: [{
		name: 'jsonschema-browser-url-base',
		setup(build) {
			// Chromium needs a host on this internal URL base. No request uses this scheme.
			build.onLoad({ filter: /jsonschema[\\/]lib[\\/]helpers\.js$/ }, async ({ path }) => {
				const contents = await readFile(path, 'utf8');
				if (contents.split("'resolve://'").length !== 2) throw new Error('The pinned jsonschema URL helper changed.');
				return { contents: contents.replace("'resolve://'", "'resolve://local-schema/'"), loader: 'js' };
			});
		},
	}],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
