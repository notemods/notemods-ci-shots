import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { readFile } from 'node:fs/promises';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

// Asciidoctor.js 3.0.4 browser build: remove the code paths this product never uses and that a static scan cannot
// tell apart from network or eval use (tools/network-gate.mjs). Each edit must match exactly the expected number of
// times, so a library update that changes the code fails the build instead of shipping unpatched.
//   - File.read and generate_data_uri_from_uri: synchronous XMLHttpRequest readers (include from disk/URL, data-uri).
//     Safe mode already blocks both; the stubs throw an IOError-like error, which Asciidoctor reports as unresolved.
//   - Kernel#instance_eval / class_eval with a string: needs the Opal compiler, which the build does not contain.
const ASCIIDOCTOR_EDITS = [
	{ from: "var xhr = new XMLHttpRequest();\n        xhr.open('GET', path, false);", to: "throw new Error('AsciiDoc Files reads no files: ' + path); var xhr;", count: 1 },
	{ from: "var xhr = new XMLHttpRequest()\n        xhr.open('GET', image_uri, false)", to: "throw new Error('AsciiDoc Files reads no URLs: ' + image_uri); var xhr", count: 1 },
	{ from: 'return new Function("Opal,self", "return " + compiled)(Opal, self);', to: 'throw new Error("AsciiDoc Files has no string eval: " + typeof compiled);', count: 2 },
];

const stubAsciidoctor = {
	name: 'stub-asciidoctor',
	setup(build) {
		build.onLoad({ filter: /@asciidoctor[\\/]core[\\/]dist[\\/]browser[\\/]asciidoctor\.js$/ }, async (args) => {
			let code = await readFile(args.path, 'utf8');
			for (const edit of ASCIIDOCTOR_EDITS) {
				const found = code.split(edit.from).length - 1;
				if (found !== edit.count) throw new Error(`stub-asciidoctor: expected ${edit.count} match(es) of ${JSON.stringify(edit.from.slice(0, 60))}, found ${found}`);
				code = code.split(edit.from).join(edit.to);
			}
			if (/XMLHttpRequest|new Function\(/.test(code)) throw new Error('stub-asciidoctor: an XMLHttpRequest or new Function is left in the library');
			return { contents: code, loader: 'js' };
		});
		// The default stylesheet for exports: comments removed (they hold a commented-out remote font @import).
		build.onLoad({ filter: /@asciidoctor[\\/]core[\\/]dist[\\/]css[\\/]asciidoctor\.css$/ }, async (args) => {
			const css = (await readFile(args.path, 'utf8')).replace(/\/\*[\s\S]*?\*\//g, '').trim();
			if (/@import|https?:\/\//.test(css)) throw new Error('stub-asciidoctor: the stylesheet still has a remote reference');
			return { contents: `/* Asciidoctor default stylesheet, MIT License */\n${css}\n`, loader: 'text' };
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
	// The browser build of Asciidoctor.js (no Node APIs, so the plugin also runs on mobile).
	mainFields: ['browser', 'module', 'main'],
	conditions: ['browser'],
	// The Asciidoctor default stylesheet goes into exported HTML files as text.
	loader: { '.css': 'text' },
	plugins: [stubAsciidoctor],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
